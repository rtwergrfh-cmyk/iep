"""Builds src/words.js: common English words (wordfreq top 30,000), minus words that are mainly
first names (gender-guesser) unless they're among the 3,000 most common words ("will", "hope", "mark").
Used only to tell capitalized ordinary words ("Listening", "Summer") from possible names in step 2.
pip install wordfreq gender-guesser"""
from wordfreq import top_n_list
import gender_guesser.detector as g
d = g.Detector()
top = top_n_list('en', 30000)
keep = []
for rank, w in enumerate(top):
    if not w.isalpha() or len(w) < 3 or not w.isascii(): continue
    if rank > 3000 and d.get_gender(w.capitalize()) != 'unknown': continue
    keep.append(w)
keep.sort()
open('src/words.js', 'w').write('/* Common English words, used only to tell ordinary capitalized words from possible names. Generated by tools/words/make_words.py (wordfreq, gender-guesser). */\n'
    "(function (root) { var W = '" + ' '.join(keep) + "'; var S = null; var api = { has: function (w) { if (!S) S = new Set(W.split(' ')); return S.has(String(w).toLowerCase()); } };\n"
    "if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.IEPWords = api; })(typeof self !== 'undefined' ? self : this);\n")
print(len(keep))
